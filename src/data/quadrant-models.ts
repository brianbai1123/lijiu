export function quadrantHaystack(id: string) {
  const model = quadrantModels[id];
  if (!model) return "";
  return [
    model.heading,
    model.intro,
    model.summary,
    ...[model.xAxis, model.yAxis].flatMap((axis) => [
      axis.name,
      axis.description,
      ...axis.ends,
    ]),
    ...model.transitions,
    ...model.quadrants.flatMap((q) => [
      q.name,
      q.definition,
      q.logic,
      q.vignette ?? "",
      q.reminder,
      ...q.examples,
      ...q.problems,
      ...q.responses,
    ]),
  ].join(" ");
}
